"""Render the ZV-composition, mode-occupancy and high-K display tables from the archived campaigns."""
import argparse
import gzip
import json
from pathlib import Path
from statistics import median

import torch

from zv_composition import METHODS, REPS, _fmt, band_word, pooled_ratio


POSTERIORS = ["WDBC", "Spambase", "Adult", "$t(3)$", "Hierarchical"]
BANDS = {"transfers": "T", "partial": "P", "parity": "E", "hurts": "H",
         "unresolved": "U", "fit-noise-limited": r"$\dagger$"}


def table(path, alignment, header, rows):
    lines = [r"% Generated by scripts/render_study_tables.py.",
             r"\begin{tabular}{" + alignment + "}", r"\toprule",
             header, r"\midrule", *rows, r"\bottomrule", r"\end{tabular}"]
    path.write_text("\n".join(lines) + "\n")


def cell(value, band, formatter):
    if value["ratio"] == 0 and band == "transfers":
        return r"$0^{*}$ T"
    lo, hi = value["ci"]
    return (r"\shortstack{" + formatter(value["ratio"]) + " " + BANDS[band]
            + r" \\{} [" + formatter(lo) + ", " + formatter(hi) + "]}")


def zv_tables(data, out):
    root = data / "zv_campaign"
    report = json.loads((root / "zv_composition.emitter.json").read_text())
    assert not report["gate_failures"] and not report["validator_failures"]
    with gzip.open(root / "zv_composition.jsonl.gz", "rt") as records:
        rows = [r for r in map(json.loads, records) if r["status"] == "accepted"]
    index = {(r["cell_index"], r["method"], r["replicate"]): r for r in rows}
    expected = {(c, m, r) for c in range(5) for m in METHODS for r in REPS}
    assert len(index) == len(rows) and set(index) == expected
    grid, diagnostics = [], []
    for ci, name in enumerate(POSTERIORS):
        result = report["cells"][str(ci)]
        for obs, label in [("o1", "Mean"), ("o2", "Pred.")]:
            for degree in [1, 2]:
                key = f"{obs}_deg{degree}"
                ws = {}
                for method in METHODS:
                    ws[method] = []
                    for rep in REPS:
                        row = index[ci, method, rep]
                        sample = torch.tensor(row[f"ws{degree}_{obs}"], dtype=torch.float64)
                        ws[method].append((rep, sample.reshape(row["G"], -1)))
                zero = pooled_ratio(ws["zero_sum"], ws["iid"])
                anti = pooled_ratio(ws["antithetic"], ws["iid"])
                assert _fmt(zero) == result[f"A_ws_{key}"], (ci, key, _fmt(zero), result[f"A_ws_{key}"])
                contrasts = [(result[f"A_{key}"], result[f"A_band_{key}"]),
                             (result[f"A_anti_{key}"], result[f"A_anti_band_{key}"]),
                             (_fmt(zero), band_word(zero)), (_fmt(anti), band_word(anti))]
                label_cells = [name if obs == "o1" and degree == 1 else "",
                               label if degree == 1 else "", str(degree)]
                values = [cell(v, b, lambda x: f"{x:.3g}") for v, b in contrasts]
                grid.append(" & ".join(label_cells + values) + r" \\[2pt]")
                # The emitter keeps log10 absolute variances even when a rounded
                # ratio is smaller than the precision of its printed columns.
                bs = [result[f"B_{m}_{key}"]["abs_log10"] for m in
                      ["iid", "zero_sum", "antithetic"]]
                logs = [bs[0][1], bs[0][0], result[f"A_ws_{key}"]["abs_log10"][1]]
                interaction = result[f"I_{key}"]
                detail = [f"{v:.3f}" for v in logs + [a - b for a, b in bs]]
                detail += [f"{interaction['log_interaction']:.2f} "
                           f"[{interaction['ci'][0]:.2f}, {interaction['ci'][1]:.2f}]"]
                diagnostics.append(" & ".join(label_cells + detail) + r" \\")
        grid.append(r"\addlinespace")
        diagnostics.append(r"\addlinespace")
    table(out / "zv_grid.tex", "llccccc",
          r" & & & \multicolumn{2}{c}{Frozen fit} & \multicolumn{2}{c}{Same-run fit} \\"
          "\n" r"\cmidrule(lr){4-5}\cmidrule(lr){6-7}"
          "\n" r"Posterior & Obs. & Degree & $C_\star$ & Pairwise & $C_\star$ & Pairwise$^p$ \\", grid)
    table(out / "zv_diagnostics.tex", "llcrrrrrrc",
          r" & & & \multicolumn{3}{c}{iid log variance} & \multicolumn{3}{c}{Log variance change} & \\"
          "\n" r"\cmidrule(lr){4-6}\cmidrule(lr){7-9}"
          "\n" r"Posterior & Obs. & Deg. & Plain & Frozen & Same-run & iid & $C_\star$ & Pairwise & Interaction \\",
          diagnostics)


def bimodal_table(data, out):
    root = data / "multimodal_campaign"
    report = json.loads((root / "multimodal_campaign.emitter.json").read_text())
    assert not report["gate_failures"] and not report["validator_failures"]
    labels = ["Mild ($a=2$)", "Intermediate ($a=3.5$)", "High barrier ($a=4$)",
              "Asymmetric ($w=0.7$)", "One-basin start", "$K=16$", r"$\eta=0.1$"]
    rows = []
    for i, label in enumerate(labels):
        c = report["cells"][str(i)]
        values = [cell(c[f"occ_ratio_{m}"], c[f"occ_band_{m}"], lambda x: f"{x:.3f}")
                  for m in ["zero_sum", "antithetic", "common"]]
        reps = c["occ_ratio_zero_sum"]["per_rep"]
        values.append(f"{median(reps):.3f} [{min(reps):.3f}, {max(reps):.3f}]")
        rows.append(" & ".join([label] + values) + r" \\[2pt]")
    table(out / "bimodal.tex", "lcccc",
          r"Setting & $C_\star$ & Pairwise & Common & $C_\star$ replicates \\", rows)


def highk_table(source, out):
    # Keep the archived, byte-verified table intact. Its long headings and
    # inline intervals are too wide for the paper at a readable type size.
    body = source.read_text().split(r"\midrule")[1].split(r"\bottomrule")[0]
    rows = []
    for line in body.strip().splitlines():
        dataset, prior, ensembles, *contrasts = line.split(r"\\")[0].strip().split(" & ")
        assert len(contrasts) == 4
        cells = [dataset, prior, ensembles]
        for contrast in contrasts:
            estimate, interval = contrast.split(" ", 1)
            cells.append(r"\shortstack{" + estimate + r" \\{} " + interval + "}")
        rows.append(" & ".join(cells) + r" \\[2pt]")
    table(out / "campaign_highk_display.tex", "lcccccc",
          r" & & & \multicolumn{2}{c}{$C_\star(8)$/iid(128)} & iid(8)/iid(128) & $C_\star(8)$/pair(8) \\"
          "\n" r"\cmidrule(lr){4-5}"
          "\n" r"Dataset & Prior & Ensembles & Main run & Repeat & Repeat & Repeat \\", rows)


if __name__ == "__main__":
    repo = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data", type=Path, default=repo / "campaigns")
    parser.add_argument("--out", type=Path, default=repo / "paper" / "tables")
    args = parser.parse_args()
    args.out.mkdir(parents=True, exist_ok=True)
    highk_table(repo / "paper/tables/campaign_highk_iid.tex", args.out)
    zv_tables(args.data, args.out)
    bimodal_table(args.data, args.out)
